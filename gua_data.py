"""64卦基础数据模块。

提供64卦的卦名、卦序、上下卦、卦符、卦辞概要，以及通过六爻编码反查卦信息的映射。
"""

from dataclasses import dataclass

TRIGRAM_UNICODE: dict[str, str] = {
    "乾": "\u2630",  # ☰
    "兑": "\u2631",  # ☱
    "离": "\u2632",  # ☲
    "震": "\u2633",  # ☳
    "巽": "\u2634",  # ☴
    "坎": "\u2635",  # ☵
    "艮": "\u2636",  # ☶
    "坤": "\u2637",  # ☷
}


def _tri(t: str) -> str:
    """返回卦名加 Unicode 卦符，如 '乾☰'。"""
    return f"{t}{TRIGRAM_UNICODE[t]}"


@dataclass(frozen=True)
class GuaInfo:
    """单卦信息。"""

    index: int          # 卦序 1-64（文王卦序）
    name: str           # 卦名，如 "乾为天"
    upper: str          # 上卦，如 "乾☰"
    lower: str          # 下卦，如 "乾☰"
    symbol: str         # Unicode 卦符，如 "䷀"
    summary: str        # 卦辞概要
    binary: int         # 六爻编码（阳=1,阴=0,初爻=低位,上爻=高位），范围0-63


def _make_gua(
    index: int,
    name: str,
    upper_trigram: str,
    lower_trigram: str,
    summary: str,
    binary: int,
) -> GuaInfo:
    """构造 GuaInfo，自动计算卦符和上下卦字符串。"""
    return GuaInfo(
        index=index,
        name=name,
        upper=_tri(upper_trigram),
        lower=_tri(lower_trigram),
        symbol=chr(0x4DC0 + index - 1),  # Unicode 卦符按文王卦序排列
        summary=summary,
        binary=binary,
    )


